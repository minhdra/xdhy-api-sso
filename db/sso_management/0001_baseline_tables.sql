CREATE TABLE IF NOT EXISTS public.system_users (
  user_id character varying(36) NOT NULL,
  user_name character varying(150) NOT NULL,
  password character varying(250) NOT NULL,
  type character varying(150) DEFAULT NULL::character varying,
  description character varying(250) DEFAULT NULL::character varying,
  online_flag smallint,
  active_flag integer NOT NULL,
  created_by_user_id character varying(36) NOT NULL,
  created_date_time timestamp without time zone NOT NULL,
  lu_updated timestamp without time zone,
  lu_user_id character varying(36) DEFAULT NULL::character varying,
  CONSTRAINT system_users_pkey PRIMARY KEY (user_id)
);

CREATE TABLE IF NOT EXISTS public.user_profiles (
  user_id character varying(250) NOT NULL,
  first_name character varying(20) DEFAULT NULL::character varying,
  middle_name character varying(20) DEFAULT NULL::character varying,
  last_name character varying(20) DEFAULT NULL::character varying,
  full_name character varying(60) DEFAULT NULL::character varying,
  avatar character varying(250) DEFAULT NULL::character varying,
  gender smallint,
  date_of_birth date,
  email character varying(150) DEFAULT NULL::character varying,
  phone_number character varying(20) DEFAULT NULL::bpchar,
  active_flag integer NOT NULL,
  created_by_user_id character varying(36) NOT NULL,
  created_date_time timestamp without time zone NOT NULL,
  lu_updated timestamp without time zone,
  lu_user_id character varying(36) DEFAULT NULL::character varying,
  CONSTRAINT user_profiles_pkey PRIMARY KEY (user_id),
  CONSTRAINT user_profiles_ibfk_1 FOREIGN KEY (user_id) REFERENCES system_users(user_id)
);
CREATE INDEX IF NOT EXISTS user_id ON public.user_profiles USING btree (user_id);

